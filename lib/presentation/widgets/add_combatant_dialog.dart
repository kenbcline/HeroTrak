import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../state/turn_engine_notifier.dart';

/// Shows the Add Combatant dialog as a modal route.
Future<void> showAddCombatantDialog(BuildContext context) {
  return showDialog<void>(
    context: context,
    builder: (context) => const AddCombatantDialog(),
  );
}

/// Character data-entry form for adding a combatant to the encounter.
///
/// Captures Name (required), an optional Faction (autocompleted from the
/// encounter's existing factions), DEX / EGO (default 10), SPD (strict
/// integer 1–12, default 3), STUN / END / BODY (default 0), and an Is NPC
/// toggle. The Archetype dropdown pre-fills DEX/EGO/SPD and Is NPC from a
/// mook template. On a valid submit the form calls
/// [TurnEngineNotifier.addCombatant], which injects the character with
/// auto-generated 6e Speed Chart phase slots.
class AddCombatantDialog extends ConsumerStatefulWidget {
  const AddCombatantDialog({super.key});

  @override
  ConsumerState<AddCombatantDialog> createState() => _AddCombatantDialogState();
}

class _AddCombatantDialogState extends ConsumerState<AddCombatantDialog> {
  /// Goon templates: pre-populated stat blocks for quick combatant entry.
  static const Map<String, ({int dex, int ego, int spd})> _archetypes =
      <String, ({int dex, int ego, int spd})>{
    'Slow Weak Goon': (dex: 8, ego: 8, spd: 2),
    'Fast Weak Goon': (dex: 15, ego: 8, spd: 4),
    'Slow Tough Goon': (dex: 10, ego: 10, spd: 2),
    'Fast Tough Goon': (dex: 18, ego: 10, spd: 5),
    'Mind-Resistant Goon': (dex: 12, ego: 15, spd: 3),
    'Mastermind / Elite Boss': (dex: 23, ego: 18, spd: 6),
  };

  /// Standard faction suggestions, extended with session factions.
  static const List<String> _defaultFactions = <String>[
    'Players',
    'Villain',
    'Civilian',
    'Law Enforcement',
  ];

  final _formKey = GlobalKey<FormState>();
  final _nameController = TextEditingController();
  final _factionController = TextEditingController();
  final _factionFocusNode = FocusNode();
  final _dexController = TextEditingController(text: '10');
  final _egoController = TextEditingController(text: '10');
  final _spdController = TextEditingController(text: '3');
  bool _isNpc = false;

  /// Whether the Name field currently holds an auto-generated archetype
  /// name (re-selecting a template replaces it; custom text is preserved).
  bool _nameIsAutoGenerated = false;

  @override
  void dispose() {
    _nameController.dispose();
    _factionController.dispose();
    _factionFocusNode.dispose();
    _dexController.dispose();
    _egoController.dispose();
    _spdController.dispose();
    super.dispose();
  }

  /// Faction suggestions: the standard set plus any custom factions used
  /// in the session.
  Iterable<String> get _factionOptions => <String>{
        ..._defaultFactions,
        for (final combatant in ref.read(turnEngineProvider).combatants)
          if (combatant.team.trim().isNotEmpty) combatant.team.trim(),
      };

  /// Pre-populates DEX / EGO / SPD and sets Is NPC from [name]'s template.
  /// With an empty (or auto-generated) Name field the template name is
  /// auto-numbered against existing combatants (e.g. `Slow Weak Goon 1`);
  /// custom names are preserved.
  void _applyArchetype(String name) {
    final archetype = _archetypes[name];
    if (archetype == null) return;
    setState(() {
      _dexController.text = '${archetype.dex}';
      _egoController.text = '${archetype.ego}';
      _spdController.text = '${archetype.spd}';
      _isNpc = true;
      if (_nameController.text.trim().isEmpty || _nameIsAutoGenerated) {
        _nameController.text = _nextAutoName(name);
        _nameIsAutoGenerated = true;
      }
    });
  }

  /// `'<template> <n>'` with `n` one past the number of same-named
  /// combatants already in the encounter.
  String _nextAutoName(String template) {
    final count = ref.read(turnEngineProvider).combatants.where((combatant) {
      final name = combatant.name.trim();
      return name == template || name.startsWith('$template ');
    }).length;
    return '$template ${count + 1}';
  }

  String? _validateName(String? value) {
    if (value == null || value.trim().isEmpty) {
      return 'Name is required';
    }
    return null;
  }

  String? _validateStat(String? value) {
    final parsed = int.tryParse(value?.trim() ?? '');
    if (parsed == null) return 'Enter a whole number';
    if (parsed < 0) return 'Must be 0 or greater';
    return null;
  }

  String? _validateSpd(String? value) {
    final parsed = int.tryParse(value?.trim() ?? '');
    if (parsed == null) return 'Enter a whole number';
    if (parsed < 1 || parsed > 12) return 'SPD must be between 1 and 12';
    return null;
  }

  void _submit() {
    if (!(_formKey.currentState?.validate() ?? false)) return;
    ref.read(turnEngineProvider.notifier).addCombatant(
          name: _nameController.text,
          dex: int.parse(_dexController.text.trim()),
          ego: int.parse(_egoController.text.trim()),
          spd: int.parse(_spdController.text.trim()),
          stun: 0,
          end: 0,
          body: 0,
          team: _factionController.text.trim(),
          isNpc: _isNpc,
        );
    Navigator.of(context).pop();
  }

  @override
  Widget build(BuildContext context) {
    return AlertDialog(
      title: const Text('Add Combatant'),
      content: SizedBox(
        width: 420,
        child: Form(
          key: _formKey,
          child: SingleChildScrollView(
            child: Column(
              mainAxisSize: MainAxisSize.min,
              children: <Widget>[
                TextFormField(
                  key: const Key('field-name'),
                  controller: _nameController,
                  decoration: const InputDecoration(labelText: 'Name'),
                  onChanged: (_) => _nameIsAutoGenerated = false,
                  validator: _validateName,
                ),
                DropdownButtonFormField<String>(
                  key: const Key('field-archetype'),
                  decoration: const InputDecoration(labelText: 'Archetype'),
                  items: <DropdownMenuItem<String>>[
                    for (final name in _archetypes.keys)
                      DropdownMenuItem<String>(value: name, child: Text(name)),
                  ],
                  onChanged: (value) {
                    if (value != null) _applyArchetype(value);
                  },
                ),
                RawAutocomplete<String>(
                  textEditingController: _factionController,
                  focusNode: _factionFocusNode,
                  optionsBuilder: (textEditingValue) {
                    final query = textEditingValue.text.toLowerCase();
                    return _factionOptions.where(
                      (faction) => faction.toLowerCase().contains(query),
                    );
                  },
                  onSelected: (selection) =>
                      setState(() => _factionController.text = selection),
                  optionsViewBuilder: (context, onSelected, options) {
                    return Align(
                      alignment: Alignment.topLeft,
                      child: Material(
                        elevation: 4,
                        child: SizedBox(
                          width: 320,
                          child: ListView.builder(
                            key: const Key('faction-options'),
                            padding: EdgeInsets.zero,
                            shrinkWrap: true,
                            itemCount: options.length,
                            itemBuilder: (context, index) {
                              final option = options.elementAt(index);
                              return ListTile(
                                title: Text(option),
                                onTap: () => onSelected(option),
                              );
                            },
                          ),
                        ),
                      ),
                    );
                  },
                  fieldViewBuilder:
                      (context, controller, focusNode, onFieldSubmitted) {
                    return TextFormField(
                      key: const Key('field-faction'),
                      controller: controller,
                      focusNode: focusNode,
                      decoration: const InputDecoration(labelText: 'Faction'),
                    );
                  },
                ),
                Row(
                  children: <Widget>[
                    Expanded(
                      child: TextFormField(
                        key: const Key('field-dex'),
                        controller: _dexController,
                        decoration: const InputDecoration(labelText: 'DEX'),
                        keyboardType: TextInputType.number,
                        validator: _validateStat,
                      ),
                    ),
                    const SizedBox(width: 12),
                    Expanded(
                      child: TextFormField(
                        key: const Key('field-ego'),
                        controller: _egoController,
                        decoration: const InputDecoration(labelText: 'EGO'),
                        keyboardType: TextInputType.number,
                        validator: _validateStat,
                      ),
                    ),
                  ],
                ),
                TextFormField(
                  key: const Key('field-spd'),
                  controller: _spdController,
                  decoration: const InputDecoration(labelText: 'SPD'),
                  keyboardType: TextInputType.number,
                  validator: _validateSpd,
                ),
                SwitchListTile(
                  key: const Key('toggle-npc'),
                  contentPadding: EdgeInsets.zero,
                  title: const Text('Is NPC'),
                  value: _isNpc,
                  onChanged: (value) => setState(() => _isNpc = value),
                ),
              ],
            ),
          ),
        ),
      ),
      actions: <Widget>[
        TextButton(
          key: const Key('cancel-add-combatant'),
          onPressed: () => Navigator.of(context).pop(),
          child: const Text('Cancel'),
        ),
        FilledButton(
          key: const Key('submit-add-combatant'),
          onPressed: _submit,
          child: const Text('Add'),
        ),
      ],
    );
  }
}